/**
 * Builds the first estimate of a sales request. Pure: the server stores the result.
 * Every value that was not given is filled with a safe default, and each default is written to the assumptions.
 */
import type { Estimate, EstimatingSettings, Material, PackagingType } from '../estimating/types';
import type { SalesRequest } from './types';
import { STYLES } from '../estimating/catalog.ts';

const TYPES: PackagingType[] = ['folding', 'corrugated', 'rigid', 'display', 'copacking'];
const MATERIAL_CATEGORY: Record<PackagingType, Material['category']> = {
  folding: 'carton',
  corrugated: 'corrugated',
  rigid: 'rigid',
  display: 'corrugated',
  copacking: 'carton',
};
const DEFAULT_QUANTITIES = [500, 1000, 2500];
const DIMENSIONS_MISSING = 'Dimensions manquantes: à confirmer';

export interface BuildEstimateInput {
  request: SalesRequest;
  materials: Material[];
  settings: EstimatingSettings;
  /** EST-YY-NNNN */
  no: string;
  ownerId: string;
  /** ISO date-time. */
  now: string;
  /** 'e_' + random hex, chosen by the caller. */
  id: string;
}

const dim = (v: number | undefined) => (typeof v === 'number' && Number.isFinite(v) && v > 0 ? Math.round(v) : 0);

export function buildEstimateDraft({ request, materials, settings, no, ownerId, now, id }: BuildEstimateInput): Estimate {
  const s = request.spec;
  const assumptions = [...request.analysis.assumptions];

  const type: PackagingType = s.type && TYPES.includes(s.type) ? s.type : 'folding';
  if (type !== s.type) assumptions.push(`Type d’emballage non précisé : ${type} retenu par défaut`);

  const styles = STYLES[type];
  const style = s.style && styles.some((x) => x.code === s.style) ? s.style : styles[0].code;
  if (style !== s.style) assumptions.push(`Style non précisé : ${style} retenu par défaut`);

  const lengthMm = dim(s.lengthMm);
  const widthMm = dim(s.widthMm);
  const heightMm = dim(s.heightMm);
  const missingDims = !lengthMm || !widthMm || !heightMm;
  if (missingDims) assumptions.push(DIMENSIONS_MISSING);

  const wanted = s.materialId ? materials.find((m) => m.id === s.materialId) : undefined;
  const material = wanted ?? materials.find((m) => m.category === MATERIAL_CATEGORY[type]) ?? materials[0];
  if (!wanted) assumptions.push(`Matériau non précisé : ${material?.name ?? 'aucun matériau au catalogue'} retenu par défaut`);

  const printProcess = s.printProcess ?? 'offset';
  if (!s.printProcess) assumptions.push('Impression non précisée : offset retenue par défaut');
  const colorsOutside = s.colorsOutside ?? 4;
  const colorsInside = s.colorsInside ?? 0;
  if (s.colorsOutside === undefined || s.colorsInside === undefined) {
    assumptions.push(`Couleurs non précisées : ${colorsOutside} extérieur / ${colorsInside} intérieur par défaut`);
  }
  const newDie = s.newDie ?? true;
  if (s.newDie === undefined) assumptions.push('Outillage : nouvelle matrice de découpe prévue par défaut');

  const requested = request.quantities.filter((q) => q > 0);
  const quantities = requested.length ? requested : DEFAULT_QUANTITIES;
  if (!requested.length) assumptions.push(`Quantités non précisées : ${DEFAULT_QUANTITIES.join(', ')} retenues par défaut`);

  const costing = request.studio.status === 'requested' || request.studio.status === 'in_progress' || missingDims;
  const action = `Créée automatiquement à partir de la demande ${request.no}`;

  return {
    id,
    no,
    status: costing ? 'costing' : 'review',
    customer: request.customer,
    contact: request.contact,
    email: request.email,
    project: request.project,
    dueDate: request.dueDate,
    ownerId,
    spec: {
      type,
      style,
      lengthMm,
      widthMm,
      heightMm,
      materialId: material?.id ?? '',
      printProcess,
      colorsOutside,
      colorsInside,
      finishes: s.finishes ?? [],
      options: s.options ?? [],
      newDie,
      notes: s.notes ?? '',
    },
    quantities,
    marginPct: settings.defaultMarginPct,
    internalNotes: '',
    createdAt: now,
    updatedAt: now,
    createdBy: ownerId || 'system',
    history: [{ at: now, userId: ownerId || 'system', action }],
    requestId: request.id,
    autoGenerated: true,
    assumptions,
    sourceFileIds: [...request.fileIds],
  };
}
