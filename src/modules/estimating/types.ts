/** Packaging estimate — structure is a first draft; business rules will be supplied later. */

export type PackagingType = 'folding' | 'corrugated' | 'rigid' | 'display' | 'copacking';

/** draft -> costing -> review (ready for the estimating manager) -> approved (back to sales as a quote) -> sent -> won | lost. */
export type EstimateStatus = 'draft' | 'costing' | 'review' | 'approved' | 'sent' | 'won' | 'lost';

export interface PackagingSpec {
  type: PackagingType;
  /** Industry style code, e.g. ECMA A20.20.03.01 (reverse tuck end) or FEFCO 0201 (RSC). */
  style: string;
  /** Interior dimensions, millimetres. */
  lengthMm: number;
  widthMm: number;
  heightMm: number;
  materialId: string;
  printProcess: 'offset' | 'flexo' | 'digital' | 'none';
  colorsOutside: number;
  colorsInside: number;
  finishes: string[];
  options: string[];
  /** New cutting die needed (tooling cost). */
  newDie: boolean;
  notes: string;
}

export interface PhotoAnalysis {
  fileName: string;
  /** Filled by the future AI analysis. */
  status: 'pending' | 'done';
  suggested?: Partial<PackagingSpec>;
}

export interface EstimateHistory {
  at: string;
  userId: string;
  action: string;
  note?: string;
}

export interface Estimate {
  id: string;
  no: string;
  status: EstimateStatus;
  customer: string;
  contact: string;
  email: string;
  project: string;
  dueDate: string;
  ownerId: string;
  spec: PackagingSpec;
  quantities: number[];
  marginPct: number;
  photo?: PhotoAnalysis;
  internalNotes: string;
  createdAt: string;
  updatedAt: string;
  createdBy: string;
  history: EstimateHistory[];
  /** Sales request this estimate answers (set by the server when it is built from a request). */
  requestId?: string;
  /** Built automatically from a request: the estimator must check it before approving. */
  autoGenerated?: boolean;
  /** What the automatic build had to assume (shown at the top of the review). */
  assumptions?: string[];
  /** Uploaded images / PDFs from the request, and sketches / dielines from the studio (ids in `files`). */
  sourceFileIds?: string[];
  dielineFileIds?: string[];
  studioNotes?: string;
}

export interface Material {
  id: string;
  code: string;
  name: string;
  category: 'carton' | 'corrugated' | 'rigid' | 'plastic';
  caliper: string;
  /** Price per m² of stock (provisional until the owner enters real supplier prices). */
  costPerM2: number;
  /** Size of the sheet the material is bought in, mm. Falls back to the settings sheet size. */
  sheetWidthMm?: number;
  sheetHeightMm?: number;
  supplier?: string;
  leadTimeDays?: number;
  minOrder?: number;
}

export type PressType = 'offset' | 'flexo' | 'digital';

/** Rates for one printing process. Every number here is provisional until confirmed in the setup wizard. */
export interface PressRate {
  /** Machine + operator cost per hour of press time. */
  hourlyRate: number;
  /** Rated speed at full colour units (sheets per hour). */
  sheetsPerHour: number;
  /** Colour units on the press: more colours than this need an extra pass. */
  units: number;
  /** Make-ready time per colour (minutes). */
  makeReadyMinPerColor: number;
  /** Waste sheets run during make-ready, per colour and per piece. */
  makeReadySheetsPerColor: number;
  /** Plate cost per colour and per piece ($). */
  platePerColor: number;
  /** Ink or toner per sheet and per colour ($). */
  inkPerSheetPerColor: number;
}

/** Material waste (%) for quantities up to `upToQty` (curve: the first step that covers the quantity applies). */
export interface WasteStep {
  upToQty: number;
  pct: number;
}

/** Finishing cost: set-up per job and run cost per 1 000 units ($). */
export interface FinishRate {
  setup: number;
  perThousand: number;
}

export interface MarginTier {
  minQty: number;
  marginPct: number;
}

export type ValidationState = 'confirmed' | 'estimate';

export interface EstimatingSettings {
  id: 'settings';
  /* ---- Legacy fields (kept so existing documents keep working; the model uses the richer fields below) ---- */
  defaultMarginPct: number;
  /** @deprecated replaced by `wasteCurve`. */
  wastePct: number;
  /** @deprecated replaced by `pressRates`. */
  printSetupPerColor: number;
  /** @deprecated replaced by `pressRates`. */
  printRunPerColorUnit: number;
  /** @deprecated replaced by `dieCostByType`. */
  dieCost: number;
  /** @deprecated replaced by `finishRates`. */
  finishSetup: number;
  /** @deprecated replaced by `finishRates`. */
  finishRunUnit: number;
  /** @deprecated replaced by `assemblyRatePerHour` / `packingSecondsPerUnit`. */
  laborPerUnit: number;
  freightPct: number;

  /* ---- Company ---- */
  companyName?: string;
  /** ISO currency code used for display. */
  currency?: string;

  /* ---- Boards, sheets and waste ---- */
  /** Default sheet the stock is bought in, mm (used when a material has no size). */
  sheetWidthMm?: number;
  sheetHeightMm?: number;
  /** Gripper / trim margin on each side of the printed sheet, mm. */
  gripperMarginMm?: number;
  /** Space between two pieces on the sheet (bleed / gutter), mm. */
  gutterMm?: number;
  /** Waste curve: percentage of extra sheets as the quantity grows. */
  wasteCurve?: WasteStep[];

  /* ---- Printing ---- */
  pressRates?: Record<PressType, PressRate>;

  /* ---- Die-cutting and tooling ---- */
  /** One-time cutting die (or wrap jig for rigid boxes) cost per type, $. Only charged when the spec says "new die". */
  dieCostByType?: Record<PackagingType, number>;
  /** Die-cutter output, sheets per hour, per type. */
  dieCutSheetsPerHour?: Record<PackagingType, number>;
  dieCutHourlyRate?: number;

  /* ---- Finishing ---- */
  /** Set-up and run cost per finish key (see FINISHES in catalog.ts). */
  finishRates?: Record<string, FinishRate>;

  /* ---- Gluing, assembly and packing ---- */
  /** Hourly rate of a manual operator (hand assembly, packing). */
  assemblyRatePerHour?: number;
  /** Hourly rate of the gluer / die-cutting line for gluing. */
  machineHourlyRate?: number;
  /** Gluer output, units per hour. */
  gluerUnitsPerHour?: number;
  /** Packing time per unit (counting, bagging, cartoning), seconds. */
  packingSecondsPerUnit?: number;
  /** Extra hand assembly time for each additional part of a display or kit, seconds. */
  secondsPerExtraPart?: number;
  /** Base hand-assembly time per style code, seconds per unit. */
  styleAssemblySeconds?: Record<string, number>;
  /** Hand-assembly time per converting option key (see OPTIONS in catalog.ts), seconds per unit. */
  optionSeconds?: Record<string, number>;

  /* ---- Overhead, freight and margin ---- */
  overheadPct?: number;
  /** Margin by quantity: the highest `minQty` reached applies (used to suggest a margin). */
  marginTiers?: MarginTier[];
  /** Margin by product type (overrides the tiers when set). */
  marginByType?: Partial<Record<PackagingType, number>>;

  /* ---- Validation ---- */
  /** State per setting group id (see SETTING_GROUPS in defaults.ts). Missing = 'estimate'. */
  validated?: Record<string, ValidationState>;
  /** Set when the owner finishes the setup wizard. */
  wizardCompletedAt?: string;
}

/** One input to a calculation, with where it came from, so the report can show how a number was reached. */
export interface TraceInput {
  label: string;
  /** English label, used by the report when the interface is in English. */
  labelEn?: string;
  value: string | number;
  unit?: string;
  source: 'spec' | 'setting' | 'material' | 'derived' | 'default';
}

/** One calculation step: what was computed, the formula in words, the inputs and the result. */
export interface TraceStep {
  key: string;
  /** French wording (primary). */
  title: string;
  /** Formula in words, French. */
  formula: string;
  inputs: TraceInput[];
  result: number;
  unit?: string;
  /** French note. */
  note?: string;
  /** English wording, used by the report when the interface is in English. */
  en?: { title: string; formula: string; note?: string };
  /** True when it uses a value that has not been validated yet (see the setup wizard). */
  provisional?: boolean;
}
